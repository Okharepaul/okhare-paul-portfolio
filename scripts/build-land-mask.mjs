// One-off generator: rasterises Natural Earth land (110m) into a small bitmask
// so the journey globe can tell land from sea without shipping map data.
// Run: node scripts/build-land-mask.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { geoContains } from "d3-geo";
import { feature } from "topojson-client";

const COLS = 240;
const ROWS = 120;
const topology = JSON.parse(readFileSync(new URL("../node_modules/world-atlas/land-110m.json", import.meta.url), "utf8"));
const land = feature(topology, topology.objects.land);

const bytes = new Uint8Array((COLS * ROWS) / 8);
let count = 0;
for (let row = 0; row < ROWS; row += 1) {
  const lat = 90 - ((row + 0.5) * 180) / ROWS;
  for (let col = 0; col < COLS; col += 1) {
    const lon = -180 + ((col + 0.5) * 360) / COLS;
    if (!geoContains(land, [lon, lat])) continue;
    const index = row * COLS + col;
    bytes[index >> 3] |= 1 << (index & 7);
    count += 1;
  }
}

const source = `/** Generated by scripts/build-land-mask.mjs from Natural Earth 110m land (public domain). Do not edit. */
export const LAND_COLS = ${COLS};
export const LAND_ROWS = ${ROWS};
export const LAND_MASK_BASE64 =
  "${Buffer.from(bytes).toString("base64")}";
`;
writeFileSync(new URL("../src/lib/globe/land-mask.ts", import.meta.url), source);
console.log(`land cells: ${count} of ${COLS * ROWS}`);
