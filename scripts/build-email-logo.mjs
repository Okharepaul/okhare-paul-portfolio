// One-off generator: renders the OP mark (public/mark.svg) as a small PNG for
// emails. Mail apps do not show SVG, so the build email carries this image
// inside itself (an inline attachment) and needs no hosting.
// Run: node scripts/build-email-logo.mjs
import { readFileSync, writeFileSync } from "node:fs";
import sharp from "sharp";

/** The mark's own box, as the site draws it. */
const VIEW_BOX = "26 42 204 172";
/** The size it is shown at in the email, in CSS pixels. */
const WIDTH = 56;
const HEIGHT = 47;
/** Rendered at three times that, so it stays sharp on phone screens. */
const SCALE = 3;
/** The band's text colour: the site's light gray, on the band's black. */
const COLOUR = "#dedede";

const symbol = readFileSync(new URL("../public/mark.svg", import.meta.url), "utf8");
const path = /<path[^>]*\sd="([^"]+)"/.exec(symbol)?.[1];
if (!path) throw new Error("No path found in public/mark.svg.");

const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${VIEW_BOX}" width="${WIDTH * SCALE}" height="${HEIGHT * SCALE}">
  <path fill="${COLOUR}" fill-rule="evenodd" d="${path}"/>
</svg>`;
const png = await sharp(Buffer.from(svg)).png({ compressionLevel: 9 }).toBuffer();

const source = `/** Generated by scripts/build-email-logo.mjs from public/mark.svg. Do not edit. */
export const EMAIL_LOGO = {
  /** Shown at this size; the image itself is ${SCALE}x, for sharp phone screens. */
  width: ${WIDTH},
  height: ${HEIGHT},
  base64:
    "${png.toString("base64")}",
} as const;
`;
writeFileSync(new URL("../src/lib/email-logo.ts", import.meta.url), source);
console.log(`email logo: ${png.length} bytes`);
